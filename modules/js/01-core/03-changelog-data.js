// 按 id 快速取方块（缓存，避免 evaluateExpression 热路径里反复 blocks.find 拖帧）
// blocks 会被 loadProjectIntoSimulator / restoreState 用「blocks = []」整体重建，
// 也会被 addBlock/removeBlock 原地 push/splice。缓存必须同时校验【数组身份】与【长度】，
// 否则「切项目 / 撤销后 block 数量恰好相同」时会继续返回【旧项目的方块对象】，
// 而 getBlockById 正是 resolveGlobalValue 解析 t.<父>_px/_xrot 的入口 ——
// 解析到幽灵块 ⇒ 子骨骼的 molang 跟随读到旧值（常常是 0）⇒ 表现为「失去父骨骼控制」
// （用户报：给子骨骼播放动画后父骨骼管不住它、pos 不像在走 molang）。
// 三个可变点（blocks=[] / push / splice）都会让身份或长度变化，故此处双判据已足够；
// 另有 invalidateBlockIdCache() 供未来新增原地替换路径时手动置脏。
let _blockIdCache = null, _blockIdCacheLen = -1, _blockIdCacheArr = null;
function invalidateBlockIdCache() { _blockIdCache = null; _blockIdCacheArr = null; _blockIdCacheLen = -1; }
function getBlockById(id) {
    if (!_blockIdCache || _blockIdCacheArr !== blocks || _blockIdCacheLen !== blocks.length) {
        _blockIdCache = new Map(blocks.map(b => [b.id, b]));
        _blockIdCacheArr = blocks;
        _blockIdCacheLen = blocks.length;
    }
    return _blockIdCache.get(id);
}
// 全局变量取值：带 sourceBlockId 的骨骼全局（如 t.A_px）按 expr 在【父块作用域】实时求值，
// 实现「纯 molang 骨骼」——父姿态一变，子块表达式 t.A_px+pR·offset 自动跟随，无需 JS 写位置。
// 不带 sourceBlockId 的用户全局维持原行为（读 .value）。depth 防止循环引用无限递归。
function resolveGlobalValue(n, g, depth) {
    if (g.sourceBlockId && depth < 32) {
        const src = getBlockById(g.sourceBlockId);
        if (src) {
            // ★ 骨骼父位置全局(px/py/pz)【只】发布父的枢轴坐标(v.xpos/ypos/zpos)，不含父 basepos / 自身旋转结果。
            //   骨骼跟随移动的是「枢轴」；basepos 是几何相对枢轴的局部偏移，由 computeTransformMatrix 的 localMat
            //   自动挂在枢轴上，会随子块 v.rotatex 跟随父旋转而整体公转，与骨骼无关。
            //   旧实现对 px/py/pz 特判用 blockWorldPos(含父 basepos) 发布父几何位置，使父 basepos 被折进子块偏移
            //   → 子块绑定后随父 basepos 位移（用户报：basepos≠0 时模型视觉移位）。现统一走 expr（即 v.xpos），
            //   骨骼与 basepos 完全正交。子块 pR 旋转矩阵仍由 t.<父>_rotatex/y/z(expr=v.rotatex) 驱动，绕父枢轴公转正确。
            //   对已为骨骼子块的父，其 v.xpos 本身是 molang，求值递归到底得到父枢轴世界坐标，链上一致。
            return evaluateExpression(g.def.expr, src.scope.vars, globalVars, g.sourceBlockId, depth + 1);
        }
    }
    return g.def.value ?? 0;
}
// ★★ 表达式编译缓存（2026-10-02 性能修复）：evaluateExpression 在渲染/刷新链路里每帧被调用数万次
//   （块数 × 全局变量数）。旧实现每次调用都 `new Function(...)` 重新编译 —— 单次编译 ~10~50µs，
//   编译产物无法被引擎长期 JIT 复用，是「导入 78 个 molang 方块后巨卡」的头号元凶。
//   表达式文本在项目内高度重复且稳定，按字符串做记忆化即可（编译失败的也缓存 null，避免反复抛错重编）。
const _exprFnCache = new Map();
const _EXPR_FN_CACHE_MAX = 8000;   // 防御性上限：极端工程也不会无限膨胀
function _getExprFn(expr) {
    if (_exprFnCache.has(expr)) return _exprFnCache.get(expr);
    let fn = null;
    try { fn = new Function('math', 'v', 't', 'q', `return (${expr})`); } catch (e) { fn = null; }
    if (_exprFnCache.size >= _EXPR_FN_CACHE_MAX) _exprFnCache.clear();
    _exprFnCache.set(expr, fn);
    return fn;
}
function evaluateExpression(expr, localVarsMap, globalVarsMap, blockId = null, _depth = 0) {
    // ★ 数字开头的 molang 访问（t.1_px / v.1_time，骨骼 id 为数字时导出/关键帧驱动会产生）：
    //   JS 的 new Function 不允许 `t.1_px` 这类属性名以数字开头，直接 SyntaxError 被 catch 吞成 0，
    //   导致数字 id 的骨骼 molang 全部失效（用户报告「骨骼动画导出再导入变成一坨」的更深层根因）。
    //   预处理成方括号下标 t["1_px"] / v["1_time"]，保持 FMBE 语义（键为字符串）且 JS 语法合法。
    if (/\b[tv]\.\d/.test(expr)) {
        expr = expr.replace(/\b([tv])\.([0-9][A-Za-z0-9_]*)/g, '$1["$2"]');
    }
    const scope = { math: angleMath, q: queryNamespace };
    const vProxy = {};
    for (let [k, obj] of localVarsMap) if (k.startsWith('v.')) vProxy[k.slice(2)] = obj.value;
    scope.v = vProxy;
    // 惰性 t 代理：仅在表达式真正访问 t.X 时才实时解析该全局变量，
    // 不再预先遍历全部全局做 G^6 级递归求值（多骨骼时会导致卡死/无限递归）。
    // 未定义的 t.X 一律返回 0（与原“未命中全局→NaN→catch 返回 0”行为一致）。
    const tProxy = new Proxy({}, {
        get(_t, n) {
            if (typeof n !== 'string') return 0;
            const g = globalVarsMap.get(n);
            return g ? resolveGlobalValue(n, g, _depth) : 0;
        }
    });
    scope.t = tProxy;
    const prev = _currentEvalBlockId;
    _currentEvalBlockId = blockId;
    const _fn = _getExprFn(expr);
    // 用 try/finally 统一收口，保证「编译失败提前返回」也一定还原 _currentEvalBlockId（此前会泄漏）
    try { return _fn ? _fn(scope.math, scope.v, scope.t, scope.q) : 0; } catch(e) { return 0; }
    finally { _currentEvalBlockId = prev; }
}

function isConstantExpr(e) { return /^\s*-?\d+(\.\d+)?\s*$/.test(e); }
function getDefaultRange(name) {
    const n = name.split('.')[1];
    if (['xpos','ypos','zpos','xbasepos','ybasepos','zbasepos'].includes(n)) return { min: -5, max: 5, step: 0.01 };
    if (['xrot','yrot','zrot'].includes(n)) return { min: -180, max: 180, step: 0.01 };
    if (n === 'extend_xrot') return { min: -90, max: 90, step: 0.01 };
    if (n === 'extend_yrot') return { min: -180, max: 180, step: 0.01 };
    if (['scale','extend_scale'].includes(n)) return { min: -5, max: 5, step: 0.01 };
    if (['rotatex','rotatey','rotatez'].includes(n)) return { min: -180, max: 180, step: 0.01 };
    return { min: -10, max: 10 , step: 0.01};
}

